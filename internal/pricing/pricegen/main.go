// Command pricegen generates the embedded price table from three datasets and
// a reviewed file of max output values, and flags what a person should look at
// (ADR 0007). It reads files only; scripts/update-price-data.sh downloads the
// datasets.
//
//	go run ./internal/pricing/pricegen generate --litellm f --genai f --modelsdev f
//	go run ./internal/pricing/pricegen check --base old-table.json
//
// See docs/price-data.md.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"
	"time"

	"github.com/kirank55/kman/internal/pricing"
)

const (
	defaultTable    = "internal/pricing/table.json"
	defaultReviewed = "internal/pricing/pricegen/maxoutput.json"
	defaultReport   = "internal/pricing/pricegen/disagreements.md"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr, time.Now))
}

func run(args []string, stdout, stderr io.Writer, now func() time.Time) int {
	var err error
	switch {
	case len(args) > 0 && args[0] == "generate":
		err = cmdGenerate(args[1:], stderr, now())
	case len(args) > 0 && args[0] == "check":
		err = cmdCheck(args[1:], stdout, stderr)
	default:
		err = errors.New("usage: pricegen generate|check [flags]")
	}
	if err != nil {
		fmt.Fprintln(stderr, "pricegen:", err)
		return 1
	}
	return 0
}

func cmdGenerate(args []string, stderr io.Writer, now time.Time) error {
	fs := flag.NewFlagSet("generate", flag.ContinueOnError)
	fs.SetOutput(stderr)
	litellm := fs.String("litellm", "", "LiteLLM's model_prices_and_context_window.json")
	genai := fs.String("genai", "", "genai-prices' prices/new_data/v2/data.json")
	modelsdev := fs.String("modelsdev", "", "models.dev's api.json")
	reviewed := fs.String("reviewed", defaultReviewed, "the reviewed max output file")
	out := fs.String("out", defaultTable, "the table to write")
	report := fs.String("report", defaultReport, "the disagreements report to write")
	if err := fs.Parse(args); err != nil {
		return err
	}
	var in inputs
	for path, into := range map[*string]*[]byte{litellm: &in.litellm, genai: &in.genai, modelsdev: &in.modelsdev, reviewed: &in.reviewed} {
		raw, err := os.ReadFile(*path)
		if err != nil {
			return err
		}
		*into = raw
	}
	if err := checkSources(in, now); err != nil {
		return err
	}
	d, rep, err := generate(in, now)
	if err != nil {
		return err
	}
	raw, err := encode(d)
	if err != nil {
		return err
	}
	if _, err := pricing.Parse(raw); err != nil {
		return err
	}
	if err := os.WriteFile(*report, reportText(rep), 0o644); err != nil {
		return err
	}
	if old, err := os.ReadFile(*out); err == nil && samePrices(old, d) {
		fmt.Fprintln(stderr, "pricegen: no price changed; the table stays as it is")
		return nil
	}
	return os.WriteFile(*out, raw, 0o644)
}

// samePrices reports whether the table in old says the same as d, whatever its
// date and source hashes, which change every week.
func samePrices(old []byte, d pricing.Data) bool {
	var was pricing.Data
	if json.Unmarshal(old, &was) != nil {
		return false
	}
	d.GeneratedAt, d.Sources = was.GeneratedAt, was.Sources
	want, err := encode(d)
	if err != nil {
		return false
	}
	have, err := encode(was)
	return err == nil && bytes.Equal(have, want)
}

// reportText is the disagreements report. It's committed, so the weekly diff
// shows the new ones.
func reportText(r *report) []byte {
	var b bytes.Buffer
	b.WriteString("# Price source disagreements\n\nGenerated by pricegen; do not edit. Each row is a value the sources state differently, in microdollars per million tokens (or tokens, for max output). The table keeps the conservative value, and a person reviews it against the provider's page. See docs/price-data.md.\n")
	fmt.Fprintf(&b, "\n## Disagreements (%d)\n\n| Section | Model | Tier | Value | litellm | genai-prices | models.dev | Kept |\n|---|---|---|---|---|---|---|---|\n", len(r.Disagreements))
	value := func(x Disagreement, source string) string {
		if v, ok := x.Values[source]; ok {
			return fmt.Sprint(v)
		}
		return ""
	}
	for _, x := range r.Disagreements {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %d |\n", x.Preset, x.Model, x.Tier, x.Field,
			value(x, "litellm"), value(x, "genai-prices"), value(x, "models.dev"), x.Kept)
	}
	list := func(title string, items []string) {
		fmt.Fprintf(&b, "\n## %s (%d)\n\n", title, len(items))
		for _, s := range items {
			fmt.Fprintf(&b, "- %s\n", s)
		}
	}
	list("Listed by a source but left out of the table", r.Dropped)
	list("In the reviewed file, but no source lists them", r.ReviewedMissing)
	return b.Bytes()
}

func cmdCheck(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("check", flag.ContinueOnError)
	fs.SetOutput(stderr)
	basePath := fs.String("base", "", "the table this one replaces; empty compares it with itself")
	tablePath := fs.String("table", defaultTable, "the table to check")
	reviewedPath := fs.String("reviewed", defaultReviewed, "the reviewed max output file")
	github := fs.Bool("github", false, "also print GitHub Actions warnings")
	if err := fs.Parse(args); err != nil {
		return err
	}
	head, err := readData(*tablePath)
	if err != nil {
		return err
	}
	base := head
	if *basePath != "" {
		if base, err = readData(*basePath); err != nil {
			return err
		}
	}
	raw, err := os.ReadFile(*reviewedPath)
	if err != nil {
		return err
	}
	reviewed, err := parseReviewed(raw)
	if err != nil {
		return err
	}
	flags := check(base, head, reviewed)
	writeFlags(stdout, flags)
	var failing []string
	counts := map[string]int{}
	for _, f := range flags {
		counts[f.Kind]++
		if f.Fails {
			failing = append(failing, f.Preset+"/"+f.Model)
		}
	}
	if *github {
		if n := counts["changed"] + counts["added"] + counts["removed"]; n > 0 {
			fmt.Fprintf(stderr, "::warning title=Price data changed::%d values changed, %d models added, %d removed. Review them in the job summary.\n", counts["changed"], counts["added"], counts["removed"])
		}
		if n := counts["max_output_equals_context"]; n > 0 {
			fmt.Fprintf(stderr, "::warning title=Max output equals the context window::%d models. See the job summary.\n", n)
		}
	}
	if len(failing) > 0 {
		return fmt.Errorf("a reviewed max output equals the context window, with no explanation in the reviewed file: %s", strings.Join(failing, ", "))
	}
	return nil
}

func readData(path string) (pricing.Data, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return pricing.Data{}, err
	}
	if _, err := pricing.Parse(raw); err != nil {
		return pricing.Data{}, fmt.Errorf("%s: %w", path, err)
	}
	var d pricing.Data
	err = json.Unmarshal(raw, &d)
	return d, err
}
